#!/usr/bin/env python3
"""Verify pinned Unicode data and generate the extension's local policy table."""

import argparse
import hashlib
import json
from pathlib import Path
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
URL = (
    "https://raw.githubusercontent.com/unicode-org/unicodetools/"
    "48afe632bf194a20bcd27c3488b49dc23274b684/"
    "unicodetools/data/security/17.0.0/confusables.txt"
)
SHA256 = "091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a"
CACHE = ROOT / "build/confusables.txt"
DESTINATION = ROOT / "extension/confusables.js"


def parse_confusables(lines):
    mappings = {}
    for number, line in enumerate(lines, 1):
        entry = line.partition("#")[0].strip()
        if not entry:
            continue
        fields = entry.split(";")
        if len(fields) != 3 or fields[2].strip() != "MA":
            raise ValueError("invalid confusables entry at line {}".format(number))
        source = chr(int(fields[0].strip(), 16))
        target = "".join(chr(int(value, 16)) for value in fields[1].split())
        if not target:
            raise ValueError("empty confusables target at line {}".format(number))
        if ord(source) > 127 and all(
            "A" <= character <= "Z" or "a" <= character <= "z"
            for character in target
        ):
            mappings[source] = target
    if not mappings:
        raise ValueError("confusables data contains no ASCII-letter mappings")
    return mappings


def verified_mappings(data):
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        raise ValueError("Unicode data SHA-256 mismatch: " + digest)
    mappings = parse_confusables(data.decode("utf-8").splitlines())
    if len(mappings) != 1407:
        raise ValueError("Unexpected Unicode 17.0.0 mapping count")
    return mappings


def generated_source(mappings):
    return (
        "// Generated by scripts/build_safari_data.py; do not edit.\n"
        "// Unicode 17.0.0; see UNICODE-LICENSE.txt and the repository NOTICE.\n"
        f"// Source SHA-256: {SHA256}\n"
        "globalThis.AntiHomographMappings = Object.freeze("
        + json.dumps(mappings, ensure_ascii=True, sort_keys=True, indent=2)
        + ");\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true", help="download the pinned data")
    parser.add_argument("--check", action="store_true", help="check without rewriting extension files")
    args = parser.parse_args()
    if args.download:
        with urllib.request.urlopen(URL, timeout=60) as response:
            data = response.read()
    else:
        if not CACHE.exists():
            parser.error("Unicode cache is missing; add --download")
        data = CACHE.read_bytes()
    mappings = verified_mappings(data)
    if args.download:
        CACHE.parent.mkdir(parents=True, exist_ok=True)
        CACHE.write_bytes(data)
    artifacts = {
        DESTINATION: generated_source(mappings),
        DESTINATION.with_name("LICENSE.txt"): (ROOT / "LICENSE").read_text(encoding="utf-8"),
        DESTINATION.with_name("UNICODE-LICENSE.txt"): (
            ROOT / "LICENSES/Unicode-3.0.txt"
        ).read_text(encoding="utf-8"),
    }
    for destination, source in artifacts.items():
        if args.check:
            if not destination.exists() or destination.read_text(encoding="utf-8") != source:
                parser.error("Extension data/license is stale; run scripts/build_safari_data.py")
        else:
            destination.write_text(source, encoding="utf-8")
    print("Verified Unicode 17.0.0: 1407 ASCII-letter mappings")


if __name__ == "__main__":
    main()
